import sys
import os

# Add project root to Python path
sys.path.append(
    os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
)

from utils.database import DatabaseUtil, db_config


import re

from typing import TypedDict

from langgraph.graph import StateGraph, START, END
from langchain_core.prompts import ChatPromptTemplate

from utils.database import DatabaseUtil, db_config
from dotenv import load_dotenv
from langchain_groq import ChatGroq

# Configure your LLM here
# Example:
# Load .env from project root
BASE_DIR = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
load_dotenv(os.path.join(BASE_DIR, ".env"))

# Get API key
api_key = os.getenv("GROQ_API_KEY")

if not api_key:
    raise ValueError("GROQ_API_KEY not found in .env file")

# Initialize Groq LLM
llm = ChatGroq(
    model="openai/gpt-oss-120b",
    temperature=0,
    api_key=api_key
)

# Import your existing LLM instead if already configured.


# --------------------------------------------------
# 1. Database
# --------------------------------------------------

db = DatabaseUtil(db_config)


# --------------------------------------------------
# 2. Clean SQL generated by the LLM
# --------------------------------------------------

def clean_sql_query(query: str) -> str:

    query = query.strip()

    # Remove Markdown code blocks
    query = re.sub(
        r"^```(?:sql)?\s*",
        "",
        query,
        flags=re.IGNORECASE
    )

    query = re.sub(r"\s*```$", "", query)

    return query.strip()


# --------------------------------------------------
# 3. Agent State
# --------------------------------------------------

class AgentSchema(TypedDict):

    question: str
    database_schema: str
    sql_query: str
    sql_query_execution_result: str
    final_answer: str


# --------------------------------------------------
# 4. SQL generation prompt
# --------------------------------------------------

sql_prompt = ChatPromptTemplate.from_messages([
    (
        "system",
        """
        You are an expert PostgreSQL SQL analyst.

        Generate a PostgreSQL query based on the user's question.

        Database schema:
        {database_schema}

        Rules:
        - Return ONLY one SQL query.
        - Use PostgreSQL syntax.
        - Only generate SELECT queries.
        - Do not generate INSERT, UPDATE, DELETE or DROP.
        - Do not use Markdown code blocks.
        - Do not include explanations.
        """
    ),
    ("human", "{question}")
])


# --------------------------------------------------
# 5. Generate SQL node
# --------------------------------------------------

def generate_sql(state: AgentSchema):

    prompt = sql_prompt.format_messages(
        question=state["question"],
        database_schema=state["database_schema"]
    )

    response = llm.invoke(prompt)

    sql_query = clean_sql_query(response.content)

    print("\nGenerated SQL:")
    print(sql_query)

    return {
        "sql_query": sql_query
    }


# --------------------------------------------------
# 6. Execute SQL node
# --------------------------------------------------

def execute_sql(state: AgentSchema):

    query = clean_sql_query(state["sql_query"])

    result = db.execute_sql(query)

    print("\nSQL Execution Result:")
    print(result)

    return {
        "sql_query_execution_result": str(result)
    }


# --------------------------------------------------
# 7. Final answer node
# --------------------------------------------------

def represent_final_answer(state: AgentSchema):

    answer_prompt = ChatPromptTemplate.from_messages([
        (
            "system",
            """
            You are a helpful data analyst.

            Answer the user's question using the SQL execution result.

            If the SQL execution result contains an error,
            explain the error clearly.

            Do not invent data.
            """
        ),
        (
            "human",
            """
            User question:
            {question}

            SQL query:
            {sql_query}

            SQL execution result:
            {sql_query_execution_result}
            """
        )
    ])

    messages = answer_prompt.format_messages(
        question=state["question"],
        sql_query=state["sql_query"],
        sql_query_execution_result=state["sql_query_execution_result"]
    )

    response = llm.invoke(messages)

    return {
        "final_answer": response.content
    }


# --------------------------------------------------
# 8. Build LangGraph
# --------------------------------------------------

graph_builder = StateGraph(AgentSchema)

graph_builder.add_node("generate_sql", generate_sql)
graph_builder.add_node("execute_sql", execute_sql)
graph_builder.add_node(
    "represent_final_answer",
    represent_final_answer
)

graph_builder.add_edge(START, "generate_sql")
graph_builder.add_edge("generate_sql", "execute_sql")
graph_builder.add_edge("execute_sql", "represent_final_answer")
graph_builder.add_edge("represent_final_answer", END)

sql_analyst = graph_builder.compile()


# --------------------------------------------------
# 9. Run SQL Analyst
# --------------------------------------------------

if __name__ == "__main__":

    database_schema = db.schema_details("public")

    user_question = input("\nAsk your database question: ")

    input_schema = {
        "question": user_question,
        "database_schema": database_schema,
        "sql_query": "",
        "sql_query_execution_result": "",
        "final_answer": ""
    }

    sql_analyst_response = sql_analyst.invoke(input_schema)

    print("\n========== FINAL ANSWER ==========")
    print(sql_analyst_response["final_answer"])
