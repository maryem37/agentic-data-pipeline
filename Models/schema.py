from pydantic import BaseModel , Field
from typing import Annotated
from operator import add

class AgentSchema(BaseModel):
    messages:  Annotated[list,add] = Field(..., description="List of messages exchanged with the agent.")
    curated_ques :str= Field(..., description="Curated question for the user.")
    prompt_query_context : str = Field(..., description="Context for the prompt query with SQL DB.")
    is_safe : Literal["Yes", "No"] = Field(..., description="Indicates whether the agent's response is safe or not.")
    generated_sql_query : str = Field(..., description="SQL query generated by the agent.")
    sql_query_execution_result : str = Field(..., description="Result of executing the generated SQL query.")
    final_answer : str = Field(..., description="Final answer provided by the agent after processing the query and execution result.")

